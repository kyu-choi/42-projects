#include "push_swap.h"

int	main(int argc, char **argv)
{
	t_node	*stack_a;
	t_node	*stack_b;

	stack_a = make_stack(argc, argv);
	stack_b = NULL;
	checking(&stack_a, &stack_b);
	if (is_sorted(stack_a) && (stack_b == NULL))
		write(1, "OK\n", 3);
	else
		write(1, "KO\n", 3);
	free_stack(&stack_a);
	free_stack(&stack_b);
	return (0);
}
