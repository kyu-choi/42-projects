#include "libft.h"

/* % ft_isspace - check for a white-space character
 * -------------------------------------------------------------------------- *
 * DESCRIPTION
 * -------------------------------------------------------------------------- *
 *	The ft_isspace() function checks whether c is one of the standard
 *	white-space characters:
 *	' ', '\t', '\n', '\r', '\v', '\f'.
 * -------------------------------------------------------------------------- *
 * RETURN VALUE
 * -------------------------------------------------------------------------- *
 *	Returns non-zero if c is white-space, otherwise returns 0.
 * -------------------------------------------------------------------------- *
 */
int	ft_isspace(int c)
{
	if (c == ' ' || c == '\t' || c == '\n')
		return (1);
	if (c == '\r' || c == '\v' || c == '\f')
		return (1);
	return (0);
}
