/* % man isdigit
 * -------------------------------------------------------------------------- *
 * SYNOPSIS
 * -------------------------------------------------------------------------- *
 *      #include <ctype.h>
 *
 * 	int	isdigit(int c);
 * -------------------------------------------------------------------------- *
 * DESCRIPTION
 * -------------------------------------------------------------------------- *
 * 	isdigit() checks for a digit (0 through 9).
 * -------------------------------------------------------------------------- *
 * RETURN VALUE
 * -------------------------------------------------------------------------- *
 *      The value returned is a non-zero value if the letter c belongs to the 
 * 	tested class, otherwise it is zero.
 * -------------------------------------------------------------------------- *
 */

int	ft_isdigit(int c)
{
	if (c >= '0' && c <= '9')
		return (0x0004);
	return (0);
}
