/* % man isprint
 * -------------------------------------------------------------------------- *
 * SYNOPSIS
 * -------------------------------------------------------------------------- *
 *      #include <ctype.h>
 *
 *	int	isprint(int c);
 * -------------------------------------------------------------------------- *
 * DESCRIPTION
 * -------------------------------------------------------------------------- *
 *	isprint() checks for printable characters, including spaces.
 * -------------------------------------------------------------------------- *
 * RETURN VALUE
 * -------------------------------------------------------------------------- *
 *      The value returned is a non-zero value if the letter c belongs to the 
 * 	tested class, otherwise it is zero.
 * -------------------------------------------------------------------------- *
 */

int	ft_isprint(int c)
{
	if (c >= 32 && c <= 126)
		return (0x0080);
	return (0);
}
