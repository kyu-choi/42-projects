/* % man isascii
 * -------------------------------------------------------------------------- *
 * SYNOPSIS
 * -------------------------------------------------------------------------- *
 * 	#include <ctype.h>
 *
 * 	int	isascii(int c);
 * -------------------------------------------------------------------------- *
 * DESCRIPTION
 * -------------------------------------------------------------------------- *
 * 	isascii() checks to see if c is a 7-bit unsigned character value 
 * 	that conforms to the ASCII character set.
 * -------------------------------------------------------------------------- *
 * RETURN VALUE
 * -------------------------------------------------------------------------- *
 *	The value returned is a non-zero value if the letter c belongs to the 
 * 	tested class, otherwise it is zero.
 * -------------------------------------------------------------------------- *
 */

int	ft_isascii(int c)
{
	if (c >= 0 && c <= 127)
		return (1);
	return (0);
}
