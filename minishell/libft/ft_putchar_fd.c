/* % Function: ft_putchar_fd - Write a character to a file descriptor
 * -------------------------------------------------------------------------- *
 * SYNOPSIS
 * -------------------------------------------------------------------------- *
 * 	void ft_putchar_fd(char c, int fd);
 * -------------------------------------------------------------------------- *
 * DESCRIPTION
 * -------------------------------------------------------------------------- *
 * 	The ft_putchar_fd() function writes the character 'c' to the given 
 * 	file descriptor. If the file descriptor is invalid, the behavior is 
 * 	undefined.
 * -------------------------------------------------------------------------- *
 * RETURN VALUE
 * -------------------------------------------------------------------------- *
 * 	None.
 * -------------------------------------------------------------------------- *
 */

#include <unistd.h>

void	ft_putchar_fd(char c, int fd)
{
	write(fd, &c, 1);
}
