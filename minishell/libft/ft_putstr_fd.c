/* % Function: ft_putstr_fd - Write a string to a file descriptor
 * -------------------------------------------------------------------------- *
 * SYNOPSIS
 * -------------------------------------------------------------------------- *
 * 	void ft_putstr_fd(char *s, int fd);
 * -------------------------------------------------------------------------- *
 * DESCRIPTION
 * -------------------------------------------------------------------------- *
 * 	The ft_putstr_fd() function writes the string 's' to the given file 
 * 	descriptor. If 's' is NULL, nothing is written.
 * -------------------------------------------------------------------------- *
 * RETURN VALUE
 * -------------------------------------------------------------------------- *
 * 	None.
 * -------------------------------------------------------------------------- *
 */

#include "libft.h"
#include <unistd.h>

void	ft_putstr_fd(char *s, int fd)
{
	if (!s)
		return ;
	write(fd, s, ft_strlen(s));
}
