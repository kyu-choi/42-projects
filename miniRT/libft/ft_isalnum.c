/* % man isalnum
 * -------------------------------------------------------------------------- *
 * SYNOPSIS
 * -------------------------------------------------------------------------- *
 * 	#include <ctype.h>
 *
 * 	int	isalnum(int c);
 * -------------------------------------------------------------------------- *
 * DESCRIPTION
 * -------------------------------------------------------------------------- *
 * 	isalnum() checks for alphanumeric characters, 
 * 	which is equivalent to (isalpha(c) || isdigit(c)).
 * -------------------------------------------------------------------------- *
 * RETURN VALUE
 * -------------------------------------------------------------------------- *
 * 	The value returned is a non-zero value if the letter c belongs to the 
 * 	tested class, otherwise it is zero.
 * -------------------------------------------------------------------------- *
 */

#include "libft.h"

int	ft_isalnum(int c)
{
	return (ft_isalpha(c) || ft_isdigit(c));
}
