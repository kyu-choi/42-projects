/* % Function: ft_putendl_fd - Write a string followed by a newline to a file 
 * 	descriptor
 * -------------------------------------------------------------------------- *
 * SYNOPSIS
 * -------------------------------------------------------------------------- *
 * 	void ft_putendl_fd(char *s, int fd);
 * -------------------------------------------------------------------------- *
 * DESCRIPTION
 * -------------------------------------------------------------------------- *
 * 	The ft_putendl_fd() function writes the string 's' to the given file 
 * 	descriptor, followed by a newline. If 's' is NULL, only a newline is 
 * 	written.
 * -------------------------------------------------------------------------- *
 * RETURN VALUE
 * -------------------------------------------------------------------------- *
 * 	None.
 * -------------------------------------------------------------------------- *
 */

#include "libft.h"

void	ft_putendl_fd(char *s, int fd)
{
	if (s)
		ft_putstr_fd(s, fd);
	ft_putchar_fd('\n', fd);
}
